"""Write the tables the docs take from the engine itself.

- docs/01-decision-list.md: the decision registry (ecomsim.decisions.REGISTRY)
- docs/08-scoring.md: the published scorecard (ecomsim.scoring.SCORECARD) and
  the runway band

Each table sits between its markers and is generated, so it says what the form
and the engine actually do. tests/test_docs.py fails when they disagree; run

    python tools/doc_tables.py            # rewrite the tables
    python tools/doc_tables.py --check    # exit 1 if a doc is out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ecomsim import scoring  # noqa: E402
from ecomsim.decisions import REGISTRY  # noqa: E402

DOCS = ROOT / "docs"
START = "<!-- {name}:start - generated by tools/doc_tables.py, do not edit by hand -->"
END = "<!-- {name}:end -->"

GROUPS = {
    "G1": "Assortment & product", "G2": "Pricing", "G3": "Marketing",
    "G4": "Channel", "G5": "Site & experience", "G6": "CRM & retention",
    "G7": "Supply & procurement", "G8": "Fulfilment", "G9": "Payments",
    "G10": "Customer service", "G11": "Technology & AI", "G12": "Finance & research",
}
KINDS = {
    "grid": "Grid, per product", "select": "Choice", "multi": "Pick many",
    "bundles": "Up to 3 three-packs", "range": "Add / drop products",
    "pct": "%", "curr": "PKR", "campaigns": "Up to 3 campaigns per channel",
    "num": "Number", "shares": "Shares to 100%", "text": "Text",
}
PRESETS = (("foundation", "F"), ("standard", "S"), ("advanced", "A"), ("expert", "E"))

# Where a lever is offered only in some games, or opens on a rule of its own
# (web/service.open_decisions, the per-game switches in web/db.py).
OFFERED = {
    "1.3": "Games set up from 2026-10-10 (`game.range_changes`); never in a game "
            "already trading when it arrived",
    "2.2": "No tile: set product by product in the 1.1 grid",
    "4.1": "Course map: session 6",
    "7.1": "Blank = the engine orders to the cover target, as far as the month can pay",
    "7.6": "Games on supplier returns (`game.returns_from`): new games from month 1",
    "11.3": "**Withdrawn** (2026-10-22): in no preset, never on the form, refunded",
    "12.6": "Games on the loan rules (`game.loans_from`): new games from month 1; "
            "blank = no new borrowing",
    "12.7": "Games on the loan rules, as 12.6",
}


def _default(spec) -> str:
    v = spec.default_when_disabled
    if v is None:
        return "blank"
    if v is False:
        return "No"
    if v in ([], ""):
        return "none"
    if spec.kind == "curr" and isinstance(v, (int, float)):
        return f"PKR {v:,.0f}"
    if spec.kind == "pct" and isinstance(v, (int, float)):
        return f"{v:.0%}"
    if spec.options:
        return next((label for value, label, _ in spec.options if value == v), str(v))
    return f"{v:g} {spec.unit}".strip() if isinstance(v, (int, float)) else str(v)


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def registry_table() -> str:
    rows = ["",
            "| # | Decision | Input | Opens | Presets | Default | What it does | Offered |",
            "|---|---|---|---|---|---|---|---|"]
    group = None
    for code, spec in sorted(REGISTRY.items(),
                             key=lambda kv: tuple(int(x) for x in kv[0].split("."))):
        if spec.group != group:
            group = spec.group
            rows.append(f"| **{group}** | **{GROUPS.get(group, group)}** | | | | | | |")
        presets = "".join(letter for name, letter in PRESETS if name in spec.presets) or "none"
        rows.append(
            f"| {code} | {_cell(spec.name)} | {KINDS.get(spec.kind, spec.kind)} | "
            f"month {spec.unlock_round} | {presets} | {_cell(_default(spec))} | "
            f"{_cell(spec.help)} | {_cell(OFFERED.get(code, ''))} |")
    counts = {name: sum(1 for s in REGISTRY.values() if name in s.presets)
              for name, _ in PRESETS}
    rows += ["",
             f"{len(REGISTRY)} decisions in the registry. Enabled per preset: "
             + ", ".join(f"{name} {n}" for name, n in counts.items())
             + ". Presets: F foundation, S standard, A advanced, E expert.", ""]
    return "\n".join(rows)


def _anchor(value: float, unit: str) -> str:
    if unit == "pct":
        return f"{value:.1%}".replace(".0%", "%")
    if unit == "x":
        return f"{value:.2f}x"
    if unit == "pp":
        return f"{value:+.1f}pp"
    if unit == "int":
        return f"{value:,.0f}"
    if unit == "pkr":
        return f"PKR {value / 1e6:+,.0f}M" if value else "PKR 0"
    return f"{value:g}"


def scorecard_table() -> str:
    rows = ["", "| Pillar | Measure | Points | 0 marks at | 50 at | 100 at |",
            "|---|---|---|---|---|---|"]
    for pillar, pts, _, measures in scoring.SCORECARD:
        rows.append(f"| **{pillar}** | | **{pts}** | | | |")
        for _, label, mpts, anchors, unit in measures:
            if anchors is None:
                rows.append(f"| | {label} | {mpts} | banded, see below | | |")
            else:
                rows.append(f"| | {label} | {mpts} | "
                            + " | ".join(_anchor(a, unit) for a in anchors) + " |")
        if not measures:
            rows.append("| | Decisions taken, and a board memo the instructor has not "
                        "rejected (rules v2, above) | 10 | | | |")
    rows += ["", "Between anchors a measure is marked in proportion; outside them it "
             "takes 0 or 100. Where 0 sits above 100 (refused and returned parcel "
             "costs) lower is better. Under rules v2 profitability is marked against "
             "the best team in the room, not these anchors (above).", ""]
    return "\n".join(rows)


# The runway band as scoring._runway_band draws it: (from, to) in months.
RUNWAY_BANDS = ((0.0, 1.5), (1.5, 3.0), (3.0, 9.0), (9.0, 16.0), (16.0, None))


def runway_table() -> str:
    rows = ["", "| Runway at the end | Marks |", "|---|---|"]
    for lo, hi in RUNWAY_BANDS:
        probe = lo + 0.01 if hi is None else (lo + hi) / 2
        label = (f"under {hi:g} months" if lo == 0 else
                 f"over {lo:g} months" if hi is None else f"{lo:g}-{hi:g} months")
        rows.append(f"| {label} | {scoring._runway_band(probe):.0f} |")
    rows.append("")
    return "\n".join(rows)


BLOCKS = (
    ("01-decision-list.md", "registry", registry_table),
    ("08-scoring.md", "scorecard", scorecard_table),
    ("08-scoring.md", "runway", runway_table),
)


def render(path: str, text: str) -> str:
    for doc, name, build in BLOCKS:
        if doc != path:
            continue
        start, end = START.format(name=name), END.format(name=name)
        head, sep, rest = text.partition(start)
        if not sep:
            raise SystemExit(f"docs/{doc} has no {name} markers")
        _, sep, tail = rest.partition(end)
        if not sep:
            raise SystemExit(f"docs/{doc} has no {name} end marker")
        text = head + start + "\n" + build() + "\n" + end + tail
    return text


def main(argv: list[str]) -> int:
    stale = []
    for doc in sorted({doc for doc, _, _ in BLOCKS}):
        path = DOCS / doc
        current = path.read_text(encoding="utf-8")
        wanted = render(doc, current)
        if wanted != current:
            stale.append(doc)
            if "--check" not in argv:
                path.write_text(wanted, encoding="utf-8")
                print(f"docs/{doc} updated")
    if stale and "--check" in argv:
        print("out of date: " + ", ".join(stale) + " - run python tools/doc_tables.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
